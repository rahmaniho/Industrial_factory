def build_alarms():
    rows = read("alarm_catalog.csv")
    L = []
    A = L.append
    sev_order = ["Critical", "Major", "Minor", "Warning"]
    sev_fa = {"Critical": "بحرانی", "Major": "مهم", "Minor": "جزئی", "Warning": "هشدار"}
    by_sev = defaultdict(list)
    by_unit = defaultdict(list)
    for r in rows:
        by_sev[r["severity"]].append(r)
        by_unit[r["unit"]].append(r)

    A("# ۹. نقشهٔ هشدارها و سطح‌بندی (Alarm Map)")
    A("")
    A("> تولید‌شده از `data/alarm_catalog.csv` — طراحی بر اساس ISA-18.2 / IEC 62682.")
    A("> **هدف عددی:** میانگین آلارم دریافتی اپراتور کمتر از **۶ آلارم در ساعت** "
      "(هدف ISA-18.2) و کمتر از **۱ آلارم در هر ۱۰ دقیقه** در شرایط پایدار.")
    A("")
    A("## ۹-۱. تعاریف سطوح و تعهد پاسخ")
    A("")
    A("| سطح | تعریف | کانال اعلان | زمان تأیید (ACK) | زمان رفع هدف | ارتقا |")
    A("|---|---|---|---|---|---|")
    A("| **بحرانی (Critical)** | تهدید جان، ایمنی، محیط‌زیست، یا توقف کامل تولید؛ "
      "یا نقض الزام قانونی/انطباق | آژیر + پوش + پیامک + تماس خودکار | ≤ ۲ دقیقه | ≤ ۳۰ دقیقه | "
      "عدم تأیید در SLA ⇒ مدیر کارخانه/مدیرعامل |")
    A("| **مهم (Major)** | تأثیر جدی بر کیفیت، تحویل یا هزینه؛ نیازمند اقدام در همان شیفت | "
      "پوش + ایمیل + نمایش داشبورد | ≤ ۱۵ دقیقه | ≤ ۸ ساعت | عدم رفع در SLA ⇒ مدیر واحد |")
    A("| **جزئی (Minor)** | نیازمند پیگیری برنامه‌ریزی‌شده | ایمیل/وظیفه | ≤ ۲ ساعت | ≤ ۷۲ ساعت | — |")
    A("| **هشدار (Warning)** | نشانهٔ روند یا انحراف خفیف؛ بدون نیاز به اقدام فوری | "
      "نمایش داشبورد/گزارش | بدون الزام | — | تکرار ⇒ ارتقا به Major |")
    A("")
    A("## ۹-۲. توزیع هشدارها")
    A("")
    A("| سطح | تعداد | سهم | ملاحظه |")
    A("|---|---|---|---|")
    for s in sev_order:
        c = len(by_sev.get(s, []))
        A(f"| {sev_fa[s]} ({s}) | {c} | {c / len(rows) * 100:.0f}٪ | "
          f"{'سهمِ بالا در کاتالوگ ایراد نیست؛ معیار، سهمِ آلارم‌های «لحظه‌ایِ» دریافتی اپراتور در عمل است (هدف < ۱۵٪)' if s == 'Critical' else '—'} |")
    A("")
    A("| واحد | تعداد هشدار | بحرانی | مهم | جزئی/هشدار |")
    A("|---|---|---|---|---|")
    for u, items in sorted(by_unit.items(), key=lambda x: -len(x[1])):
        cc = sum(1 for i in items if i["severity"] == "Critical")
        mm = sum(1 for i in items if i["severity"] == "Major")
        oo = len(items) - cc - mm
        A(f"| `{u}` | {len(items)} | {cc} | {mm} | {oo} |")
    A("")
    A("## ۹-۳. کاتالوگ هشدارها")
    A("")
    for s in sev_order:
        items = by_sev.get(s, [])
        if not items:
            continue
        A(f"### سطح {sev_fa[s]} ({s}) — {len(items)} هشدار")
        A("")
        A("| شناسه | واحد | هشدار | محرک | مسئول | اعلان | SLA تأیید | اقدام خودکار | ارتقا |")
        A("|---|---|---|---|---|---|---|---|---|")
        for r in items:
            A(f"| `{r['id']}` | {r['unit']} | {r['alarm_fa']} | {r['trigger']} | {r['owner_role']} | "
              f"{r['notification']} | {r['response_sla']} | {r['auto_action']} | "
              f"{r['escalation'] if r['escalation'] != '-' else '—'} |")
        A("")
    A("## ۹-۴. اصول مهندسی آلارم (Alarm Rationalization)")
    A("")
    A("| اصل | شرح | معیار پذیرش |")
    A("|---|---|---|")
    A("| هر آلارم باید «اقدام‌پذیر» باشد | اگر اپراتور نمی‌تواند کاری بکند، آلارم نیست؛ گزارش است | "
      "حذف یا تبدیل به گزارش |")
    A("| هر آلارم یک «مالک» دارد | مسئول پاسخ مشخص باشد | ستون مالک در کاتالوگ خالی نباشد |")
    A("| اولویت‌بندی بر اساس پیامد | شدت × فوریت | انطباق با جدول ۹-۱ |")
    A("| حذف آلارم‌های تکراری/مشتق | یک وضعیت ⇒ یک آلارم | بررسی در ممیزی آلارم |")
    A("| پایش «آلارم‌های مزاحم» (Chattering) | بیش از ۳ بار در دقیقه ⇒ نقص طراحی | صفرِ پایدار |")
    A("| سرکوبِ کنترل‌شده (Shelving) | فقط با مجوز و زمان‌دار | ثبت در Audit |")
    A("| آلارم‌های خاموش/غیرفعال | نیازمند مجوز مستند و بازنگری دوره‌ای | زیر ۱٪ کل |")
    A("")
    A("**شاخص‌های سلامت سیستم آلارم** (گزارش ماهانه):")
    A("")
    A("| شاخص | هدف |")
    A("|---|---|")
    A("| میانگین آلارم در ساعت (اپراتور) | ≤ ۶ |")
